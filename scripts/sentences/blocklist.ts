/** Tags starting with this mark ask for a fix or a check: "@change", "@needs native check"... */
export const MAINTENANCE_TAG_PREFIX = '@';

export function isBlockedTag(tag: string): boolean {
  const plain = tag.trim().toLowerCase();
  return BLOCKED_TAGS.has(plain) || plain.startsWith(MAINTENANCE_TAG_PREFIX);
}

