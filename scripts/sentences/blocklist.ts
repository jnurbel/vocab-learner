/** Lowercase letters without accents, split on anything else. */
function plainWords(text: string): string[] {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/\p{Mn}/gu, '')
    .split(/[^\p{L}]+/u)
    .filter((word) => word !== '');
}

export function isBlockedChinese(text: string): boolean {
  return BLOCKED_CHINESE.some((word) => text.includes(word));
}

export function isBlockedTranslation(text: string): boolean {
  return plainWords(text).some((word) => BLOCKED_TRANSLATION_WORDS.has(word));
}
