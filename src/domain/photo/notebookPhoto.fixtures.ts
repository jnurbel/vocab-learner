import type { Box, DetectedBlock } from './photoBlocks';

function block(
  [x, y, width, height]: readonly [number, number, number, number],
  chinese: string,
  chineseConfidence: number,
  latin: string,
  latinConfidence: number,
): DetectedBlock {
  const box: Box = { x, y, width, height };
  return {
    box,
    chinese: { text: chinese, confidence: chineseConfidence },
    latin: { text: latin, confidence: latinConfidence },
  };
}

